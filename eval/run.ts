import { writeFileSync } from 'node:fs';
import { performance } from 'node:perf_hooks';
import { random, scenarios } from './scenarios.js';

const args = process.argv.slice(2);
const option = (name: string, fallback: number) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? Number(args[index + 1]) : fallback;
};
const trials = option('trials', 25);
const seed = option('seed', 20260913);
const write = args.includes('--write');
if (!Number.isInteger(trials) || trials < 1 || trials > 1000 || !Number.isInteger(seed)) {
  console.error('Usage: npm run eval -- [--trials 1-1000] [--seed integer] [--write]');
  process.exit(2);
}

export interface ScenarioResult {
  id: string; title: string; proves: string;
  trials: number; passed: number;
  /** Failure reasons with varying values removed, and how many trials hit each. */
  failures: Record<string, number>;
  p50ms: number; p95ms: number;
}

const results: ScenarioResult[] = [];
for (const [index, scenario] of scenarios.entries()) {
  const failures: Record<string, number> = {};
  const durations: number[] = [];
  let passed = 0;
  for (let trial = 0; trial < trials; trial++) {
    const rng = random(seed + index * 100_000 + trial);
    const started = performance.now();
    let reasons: string[];
    try { reasons = await scenario.run(rng); }
    catch (error) { reasons = [`crashed: ${(error as Error).message}`]; }
    durations.push(performance.now() - started);
    if (!reasons.length) passed++;
    for (const reason of new Set(reasons.map(r => r.replace(/"[^"]*"/g, '"…"')))) failures[reason] = (failures[reason] ?? 0) + 1;
  }
  durations.sort((a, b) => a - b);
  const percentile = (p: number) => Math.round(durations[Math.min(durations.length - 1, Math.floor(p * durations.length))]);
  results.push({ id: scenario.id, title: scenario.title, proves: scenario.proves, trials, passed, failures, p50ms: percentile(0.5), p95ms: percentile(0.95) });
}

const total = { trials: results.reduce((n, r) => n + r.trials, 0), passed: results.reduce((n, r) => n + r.passed, 0) };
const rate = (r: { passed: number; trials: number }) => `${((100 * r.passed) / r.trials).toFixed(1)}%`;

console.log(`Aftercare evaluation · seed ${seed} · ${trials} trials per scenario\n`);
for (const r of results) console.log(`${r.title.padEnd(40)} ${`${r.passed}/${r.trials}`.padStart(9)} ${rate(r).padStart(7)}  p50 ${r.p50ms}ms  p95 ${r.p95ms}ms`);
console.log(`${'Total'.padEnd(40)} ${`${total.passed}/${total.trials}`.padStart(9)} ${rate(total).padStart(7)}`);
for (const r of results) for (const [reason, count] of Object.entries(r.failures)) console.log(`  ✗ ${r.title}: ${reason} (${count} of ${r.trials})`);

if (write) {
  const date = new Date().toISOString().slice(0, 10);
  writeFileSync('eval/results.json', `${JSON.stringify({ generatedAt: new Date().toISOString(), seed, trialsPerScenario: trials, total, scenarios: results }, null, 2)}\n`);
  const failureLines = results.flatMap(r => Object.entries(r.failures).map(([reason, count]) => `- ${r.title}: ${reason} (${count} of ${r.trials})`));
  writeFileSync('EVALUATION.md', [
    '# Evaluation',
    '',
    `Generated by \`npm run eval -- --write\` on ${date} with seed ${seed} and ${trials} trials per scenario.`,
    '',
    'Each trial runs onboarding-agent against simulated GitHub, Linear, and Slack APIs that also',
    'hold unrelated records, then judges the result by the apps’ final state and the requests they',
    'actually handled, never by Aftercare’s own claims. Team size, names, the timing of human edits,',
    'which write fails, and hostile content vary between trials; the seed reproduces them.',
    '',
    '| Scenario | What passing shows | Passed | p50 / p95 |',
    '| --- | --- | --- | --- |',
    ...results.map(r => `| ${r.title} | ${r.proves} | ${r.passed}/${r.trials} (${rate(r)}) | ${r.p50ms} / ${r.p95ms} ms |`),
    `| **Total** | | **${total.passed}/${total.trials} (${rate(total)})** | |`,
    '',
    failureLines.length ? '## Failures\n\n' + failureLines.join('\n') : 'No trial failed.',
    '',
    'These trials use simulated apps with the real APIs’ request and response shapes. Results against',
    'real accounts, and the problems this evaluation found, are recorded in [VALIDATION.md](VALIDATION.md).',
    '',
  ].join('\n'));
  console.log('\nWrote EVALUATION.md and eval/results.json');
}
process.exitCode = total.passed === total.trials ? 0 : 1;
